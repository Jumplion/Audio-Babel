/**
 * JavaScript wrapper for Audio Index WASM module
 * Provides a clean API for using the C++ library in the browser
 * Serverless version for docs folder (GitHub Pages)
 */

import { createWavFile } from '../utils/wavUtils.js';
import { bytesToBase64Chunked } from '../utils/base64.js';

class AudioIndexWASM {
    constructor() {
        this.module = null;
        this.initialized = false;
    }

    /**
     * Initialize the WASM module
     * @returns {Promise<void>}
     */
    async initialize() {
        if (this.initialized) {
            return;
        }

        console.log('Loading Audio Index WASM module...');
        
        try {
            // Load the module (generated by Emscripten with -sEXPORT_ES6=1)
            // Path relative to docs/js/core/ -> ../../wasm/audio-index.js
            const AudioIndexModule = (await import('../../wasm/audio-index.js')).default;
            
            // Initialize with cache-busting for the .wasm file
            // Update this version number whenever you rebuild the WASM module
            const wasmVersion = '9';
            
            // Determine the correct base path based on the environment
            // For localhost, use absolute path from root; for GitHub Pages, include repo name
            const isLocalhost = window.location.hostname === 'localhost' || window.location.hostname === '127.0.0.1';
            const wasmBasePath = isLocalhost 
                ? '/wasm/'  // Absolute path from server root (docs/)
                : `${window.location.origin}/Audio-Babel/wasm/`;
            
            console.log(`Environment: ${isLocalhost ? 'localhost' : 'production'}`);
            console.log(`WASM base path: ${wasmBasePath}`);
            
            this.module = await AudioIndexModule({
                locateFile: (path) => {
                    if (path.endsWith('.wasm')) {
                        const fullPath = `${wasmBasePath}${path}?v=${wasmVersion}`;
                        console.log(`Loading WASM from: ${fullPath}`);
                        return fullPath;
                    }
                    return path;
                }
            });
            
            this.initialized = true;
            console.log('✓ Audio Index WASM module loaded successfully');
            console.log('Available functions:', Object.keys(this.module).filter(k => typeof this.module[k] === 'function'));
        } catch (error) {
            console.error('Failed to load WASM module:', error);
            throw error;
        }
    }

    /**
     * Ensure module is initialized before use
     * @private
     */
    _ensureInitialized() {
        if (!this.initialized) {
            throw new Error('WASM module not initialized. Call initialize() first.');
        }
    }

    /**
     * Reconstruct audio data from a base64 index
     * @param {string} base64Index - Base64-encoded index (URL-safe, no padding)
     * @returns {Uint8Array} PCM sample data
     */
    reconstructAudioFromIndex(base64Index) {
        this._ensureInitialized();

        const result = this.module.reconstructAudio(base64Index);
        if (!result) {
            throw new Error('Failed to reconstruct audio from index');
        }
        return result;
    }

    /**
     * Convert audio samples to WAV format (client-side)
     * @param {Uint8Array} samples - PCM samples
     * @param {number} sampleRate - Sample rate
     * @param {number} bitDepth - Bit depth
     * @param {number} channels - Channel count
     * @returns {Blob} WAV file blob
     */
    samplesToWav(samples, sampleRate = 44100, bitDepth = 16, channels = 1) {
        return createWavFile(samples, sampleRate, bitDepth, channels);
    }

    /**
     * Convert audio samples to a base64-encoded WAV file (for embedding in JSON results)
     * @param {Uint8Array} samples - PCM samples
     * @param {number} sampleRate - Sample rate
     * @param {number} bitDepth - Bit depth
     * @param {number} channels - Channel count
     * @returns {Promise<string>} Base64-encoded WAV file
     */
    async samplesToWavBase64(samples, sampleRate = 44100, bitDepth = 16, channels = 1) {
        const wavBlob = this.samplesToWav(samples, sampleRate, bitDepth, channels);
        const wavBytes = new Uint8Array(await wavBlob.arrayBuffer());
        return bytesToBase64Chunked(wavBytes);
    }
}

// Export for use in modules
export default AudioIndexWASM;

// Also make available globally for non-module scripts
if (typeof window !== 'undefined') {
    window.AudioIndexWASM = AudioIndexWASM;
}

console.log('✅ audioIndexWasm.js loaded - WASM wrapper ready');
